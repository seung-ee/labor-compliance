"""급여 계산 — 항목마다 근거 조문과 적용 여부를 달고 나온다.

금액만 주는 계산기는 이미 많다. 이 계산기의 존재 이유는 **"왜 0원인지"를
조문으로 설명하는 것**이다. 5인 미만 사업장에서 가산수당이 0원인 것은
버그가 아니라 시행령 별표 1의 결과다.

적용 여부는 build_matrix 의 매트릭스를 읽는다. 별도 로직을 두지 않는다.
공제(4대보험·소득세)는 아직 없다. config/rates/ 가 비어 있다.
"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_matrix import build, applies

HERE = os.path.dirname(os.path.abspath(__file__))
_rows = None


def matrix():
    global _rows
    if _rows is None:
        _rows = build()
    return _rows


def 적용되나(조, 항=None, 소규모=True):
    """이 조문이 이 사업장에 적용되는가.

    ⚠ 매트릭스는 **"상시 4명 이하 사업장에 적용되는가"**만 답한다.
    5인 이상 사업장은 근로기준법이 전부 적용되므로 매트릭스를 볼 이유가 없다.
    매트릭스를 일반 적용 판정으로 쓰면 5인 이상에도 가산수당이 0원으로 나온다."""
    if not 소규모:
        return True
    return applies(matrix(), 조, 항)


def min_wage(기준일):
    """기준일이 속한 연도의 최저임금. 고시는 연 단위로 적용기간이 정해진다."""
    p = os.path.join(HERE, 'data/rates/minimum-wage.json')
    if not os.path.exists(p):
        return None
    d = json.load(open(p))['연도']
    return d.get(기준일[:4])


def calc(시급, 주소정근로시간, 실근로시간, 상시근로자수, 기준일,
         야간시간=0, 휴일시간=0, 개근=True):
    """1주 단위 지급액(세전). 공제는 포함하지 않는다."""
    소규모 = 상시근로자수 < 5
    초단시간 = 주소정근로시간 < 15          # 근기법 제18조제3항
    항목, 경고 = [], []

    def add(name, 금액, 근거, 적용, 산식=None, 사유=None):
        r = {'항목': name, '금액': int(round(금액)), '근거': 근거, '적용': 적용}
        if 산식: r['산식'] = 산식
        if 사유: r['사유'] = 사유
        항목.append(r)

    # 1) 기본급 — 실제 일한 시간 전부에 대한 임금. 가산은 별도 항목이다.
    add('기본급', 실근로시간 * 시급, '근로기준법 제43조', True,
        f'{실근로시간:g}시간 × {시급:,}원')

    # 2) 주휴수당 — 제55조제1항. 규모와 무관하게 두 가지 요건이 먼저 걸린다.
    #    제18조제3항(주 15시간 미만 제외)과 시행령 제30조제1항(소정근로일 개근).
    주휴적용 = 적용되나('제55조', 1, 소규모)   # 제55조제1항은 5인 미만도 적용
    if 초단시간:
        add('주휴수당', 0, '근로기준법 제18조제3항', False,
            사유='1주 소정근로시간 15시간 미만은 제55조가 적용되지 않는다')
    elif not 개근:
        add('주휴수당', 0, '근로기준법 시행령 제30조제1항', False,
            사유='유급휴일은 1주 소정근로일을 개근한 자에게 주어진다')
    else:
        # 단시간근로자는 통상근로자(주 40시간) 기준으로 비례 산정한다(제18조제1항).
        # 법문에 공식이 직접 있지는 않다. 행정해석·실무 기준이다.
        시간 = min(주소정근로시간, 40) / 40 * 8
        add('주휴수당', 시간 * 시급, '근로기준법 제55조제1항 + 시행령 제30조제1항',
            주휴적용, f'{시간:.1f}시간 × {시급:,}원 (주 {주소정근로시간:g}시간 비례)')

    # 3) 가산수당 — 제56조. 5인 미만은 별표 1에 없어 통째로 미적용이다.
    #    연장근로의 정의 자체가 제53조를 참조하는데 제53조도 5인 미만 미적용이라,
    #    5인 미만 사업장에는 '연장근로'라는 개념이 성립하지 않는다.
    가산적용 = 적용되나('제56조', None, 소규모)
    연장시간 = max(0, 실근로시간 - 40) if not 소규모 else 0
    사유 = '5인 미만 사업장 미적용 (근로기준법 시행령 별표 1)' if 소규모 else None
    for name, 시간, 배율, 조항 in [
            ('연장근로 가산', 연장시간, 0.5, '제56조제1항'),
            ('야간근로 가산', 야간시간, 0.5, '제56조제3항'),
            ('휴일근로 가산', min(휴일시간, 8), 0.5, '제56조제2항제1호'),
            ('휴일 8시간 초과분 가산', max(0, 휴일시간 - 8), 1.0, '제56조제2항제2호')]:
        if 시간 <= 0 and 가산적용:
            continue
        add(name, 0 if not 가산적용 else 시간 * 시급 * 배율,
            f'근로기준법 {조항}', bool(가산적용),
            None if not 가산적용 else f'{시간:g}시간 × {시급:,}원 × {배율:g}', 사유)

    # 4) 최저임금 — 최저임금법 제6조. 사업장 규모와 무관하게 적용된다.
    mw = min_wage(기준일)
    if mw is None:
        경고.append('최저임금 데이터 없음 — build_rates.py 실행 필요')
    elif 시급 < mw['시간급']:
        경고.append(f"최저임금 미달: 시급 {시급:,}원 < {기준일[:4]}년 {mw['시간급']:,}원 "
                    f"({mw['근거']['고시']}, 최저임금법 제6조)")

    if 소규모:
        경고.append('상시 4명 이하 사업장이다. 연차휴가(제60조), 가산수당(제56조), '
                    '부당해고 제한(제23조제1항), 공휴일 유급(제55조제2항)이 적용되지 않는다')

    return {'기준일': 기준일, '상시근로자수': 상시근로자수, '5인미만': 소규모,
            '합계': sum(r['금액'] for r in 항목), '항목': 항목, '경고': 경고}


def render(r):
    out = [f"기준일 {r['기준일']} · 상시 {r['상시근로자수']}명"
           f"{' (5인 미만)' if r['5인미만'] else ''}", '']
    for x in r['항목']:
        mark = ' ' if x['적용'] else '×'
        out.append(f"  {mark} {x['항목']:<22} {x['금액']:>10,}원   {x['근거']}")
        if x.get('산식'): out.append(f"      {x['산식']}")
        if x.get('사유'): out.append(f"      → {x['사유']}")
    out += ['', f"  {'합계':<24} {r['합계']:>10,}원 (세전, 공제 전)"]
    for w in r['경고']:
        out.append(f"\n  ⚠ {w}")
    return '\n'.join(out)


def test():
    기준 = dict(시급=12000, 주소정근로시간=40, 실근로시간=45, 기준일='2026-06-01')
    소 = calc(**기준, 상시근로자수=4)
    대 = calc(**기준, 상시근로자수=5)

    # 같은 입력, 규모만 다르면 결과가 갈려야 한다. 이 계산기의 존재 이유다.
    assert 소['합계'] != 대['합계'], '5인 미만/이상이 같은 금액이면 매트릭스가 안 붙은 것'
    ext = lambda r, n: next(x for x in r['항목'] if x['항목'] == n)
    assert ext(소, '연장근로 가산')['금액'] == 0 and not ext(소, '연장근로 가산')['적용']
    assert '별표 1' in ext(소, '연장근로 가산')['사유']
    assert ext(대, '연장근로 가산')['금액'] == 5 * 12000 * 0.5, '5시간 연장 × 50%'
    assert 대['합계'] - 소['합계'] == 30000

    # 주휴수당: 규모와 무관하게 적용된다
    assert ext(소, '주휴수당')['금액'] == 8 * 12000 and ext(소, '주휴수당')['적용']

    # 초단시간(주 15시간 미만)은 규모와 무관하게 주휴가 없다 — 제18조제3항
    짧 = calc(시급=12000, 주소정근로시간=12, 실근로시간=12, 상시근로자수=9, 기준일='2026-06-01')
    j = ext(짧, '주휴수당')
    assert j['금액'] == 0 and '제18조제3항' in j['근거'], j

    # 개근하지 않으면 주휴가 없다 — 시행령 제30조제1항
    결 = calc(**기준, 상시근로자수=9, 개근=False)
    assert ext(결, '주휴수당')['금액'] == 0 and '제30조' in ext(결, '주휴수당')['근거']

    # 단시간 비례: 주 20시간이면 4시간분
    반 = calc(시급=12000, 주소정근로시간=20, 실근로시간=20, 상시근로자수=3, 기준일='2026-06-01')
    assert ext(반, '주휴수당')['금액'] == 4 * 12000

    # 최저임금 미달 경고 — 규모 무관
    낮 = calc(시급=9000, 주소정근로시간=40, 실근로시간=40, 상시근로자수=3, 기준일='2026-06-01')
    assert any('최저임금 미달' in w for w in 낮['경고']), 낮['경고']
    assert not any('최저임금 미달' in w for w in 소['경고'])

    # 모든 항목이 근거 조문을 달고 있어야 한다. 인용 검증 게이트가 이걸 본다.
    for x in 소['항목'] + 대['항목']:
        assert x['근거'].startswith('근로기준법'), x
    print('ok: 5인 미만/이상 분기, 주휴 요건 3종, 최저임금 경고 정상')


if __name__ == '__main__':
    if '--test' in sys.argv:
        test()
    else:
        for n in (4, 5):
            print(render(calc(시급=12000, 주소정근로시간=40, 실근로시간=45,
                              상시근로자수=n, 기준일='2026-06-01')))
            print('\n' + '─' * 70 + '\n')
